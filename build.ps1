# Builds "AC Black Flag Resynced - Unity Sprint Mod.msi" from this source folder.
#
#   powershell -ExecutionPolicy Bypass -File build.ps1 -FromMsi "path\to\AC Black Flag Resynced - Unity Sprint Mod.msi"
#       takes the two input files (see README) out of a released MSI first, then builds
#   powershell -ExecutionPolicy Bypass -File build.ps1
#       builds from inputs\ (place the two input files there yourself)
#
# Output: out\AC Black Flag Resynced - Unity Sprint Mod.msi (unsigned; see README for signing)
#
# Needs: Windows, WiX Toolset 3.14 (set -WixDir or the WIX environment variable), Visual Studio C++ build tools
# (found with vswhere, or set -VcVars), and the .NET Framework 4 C# compiler that ships with Windows.
# Both input files are checked against their SHA-256 here, and again by SprintPatch.exe at install time.
param(
    [string]$FromMsi,
    [string]$WixDir = $(if ($env:WIX) { Join-Path $env:WIX 'bin' } else { '' }),
    [string]$VcVars = ''
)
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
$inputs = Join-Path $here 'inputs'
$motionPath = Join-Path $inputs 'Unity_Sprint_680cms.Animation'
$libPath = Join-Path $inputs 'oo2core_9_win64.dll'
$MOTION_SHA = '37128cb7739139d1e077efc8113ba7326fbe4fcf28b946e246b894186c8e9fba'    # the new sprint animation
$ORIGINAL_SHA = '40b0b1bdf0e30dedacea487b59edf686f7ab2191e96a73067eb07e5ce426009d'  # the game's original run animation entry
$LIBRARY_SHA = 'd484c81158b4e6edb593de75b1573992e304b008c133c62e7d383eacfd3da995'   # oo2core_9_win64.dll as shipped with AnvilToolkit

$obj = Join-Path $here 'obj'
$out = Join-Path $here 'out'
foreach ($d in $obj, $out, $inputs) { New-Item -ItemType Directory -Force -Path $d | Out-Null }

# --- optional: take the two inputs out of a released MSI (an administrative install only unpacks files;
#     it does not install anything or touch the game)
if ($FromMsi) {
    $x = Join-Path $obj 'from-msi'
    if (Test-Path $x) { Remove-Item -Recurse -Force $x }
    $p = Start-Process msiexec.exe -ArgumentList @('/a', "`"$((Resolve-Path $FromMsi).Path)`"", '/qn', "TARGETDIR=`"$x`"") -Wait -PassThru
    if ($p.ExitCode) { throw "msiexec /a failed ($($p.ExitCode))" }
    foreach ($n in 'Unity_Sprint_680cms.Animation', 'oo2core_9_win64.dll') {
        $f = Get-ChildItem $x -Recurse -File -Filter $n | Select-Object -First 1
        if (-not $f) { throw "$n not found in the MSI" }
        Copy-Item $f.FullName (Join-Path $inputs $n) -Force
    }
}

function Sha([byte[]]$b) { ([Security.Cryptography.SHA256]::Create().ComputeHash($b) | ForEach-Object { $_.ToString('x2') }) -join '' }
foreach ($f in $motionPath, $libPath) { if (-not (Test-Path $f)) { throw "Missing input: $f (see README)" } }
if ((Sha ([IO.File]::ReadAllBytes($motionPath))) -ne $MOTION_SHA) { throw 'Animation hash mismatch' }
if ((Sha ([IO.File]::ReadAllBytes($libPath))) -ne $LIBRARY_SHA) { throw 'Oodle library hash mismatch' }

if (-not $WixDir -or -not (Test-Path (Join-Path $WixDir 'candle.exe'))) { throw 'WiX Toolset 3.14 not found: pass -WixDir <folder with candle.exe>' }
if (-not $VcVars) {
    $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
    if (Test-Path $vswhere) {
        $vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
        if ($vs) { $VcVars = Join-Path $vs 'VC\Auxiliary\Build\vcvars64.bat' }
    }
}
if (-not $VcVars -or -not (Test-Path $VcVars)) { throw 'Visual C++ build tools not found: pass -VcVars <path of vcvars64.bat>' }

# --- file names and hashes the engine checks (the files themselves are installed next to it)
@"
// Generated by build.ps1 - do not edit.
using System.IO;
using System.Reflection;
using System.Security.Cryptography;
static class Payload
{
    public const string MOTION_SHA = "$MOTION_SHA";
    public const string ORIGINAL_SHA = "$ORIGINAL_SHA";
    public const string LIBRARY_SHA = "$LIBRARY_SHA";
    public const string Library = "oo2core_9_win64.dll", Motion = "Unity_Sprint_680cms.Animation";
    static string Here(string name) { return Path.Combine(Path.GetDirectoryName(Assembly.GetExecutingAssembly().Location), name); }
    public static byte[] Read(string name) { string p = Here(name); return File.Exists(p) ? File.ReadAllBytes(p) : new byte[0]; }
    public static bool Ok(string name, string sha)
    {
        byte[] b = Read(name); if (b.Length == 0) return false;
        using (SHA256 h = SHA256.Create()) return System.BitConverter.ToString(h.ComputeHash(b)).Replace("-", "").ToLowerInvariant() == sha;
    }
}
"@ | Set-Content -Path (Join-Path $obj 'Payload.cs') -Encoding utf8

# --- compile the engine (no embedded resources)
$exe = Join-Path $obj 'SprintPatch.exe'
& $csc /nologo /target:winexe /platform:x64 /optimize+ "/out:$exe" (Join-Path $here 'src\SprintPatch.cs') (Join-Path $obj 'Payload.cs')
if ($LASTEXITCODE) { throw 'engine compile failed' }

# --- compile the custom-action DLL (static C runtime, so it needs nothing else installed)
$dll = Join-Path $obj 'ModActions.dll'
$cpp = Join-Path $here 'src\ModActions.cpp'
cmd /c "`"$VcVars`" >nul && cl /nologo /O2 /MT /LD /EHsc /W3 /DUNICODE /D_UNICODE `"$cpp`" /Fo`"$obj\\`" /Fe`"$dll`" /link /NOLOGO msi.lib"
if ($LASTEXITCODE) { throw 'custom action compile failed' }

# --- installer artwork, cut from src\art.png (1672 x 941) at 1.5x the dialogs' 100%-scale pixel size
Add-Type -AssemblyName System.Drawing
function Bmp($w, $h, $draw, $path) {
    $b = New-Object System.Drawing.Bitmap $w, $h; $g = [System.Drawing.Graphics]::FromImage($b)
    $g.SmoothingMode = 'AntiAlias'; $g.TextRenderingHint = 'ClearTypeGridFit'
    & $draw $g; $g.Dispose(); $b.Save($path, [System.Drawing.Imaging.ImageFormat]::Bmp); $b.Dispose()
}
$art = [System.Drawing.Image]::FromFile((Join-Path $here 'src\art.png'))
function Put($g, $sx, $sy, $sw, $sh, $dx, $dy, $dw, $dh) {
    $g.InterpolationMode = 'HighQualityBicubic'; $g.PixelOffsetMode = 'HighQuality'
    $g.DrawImage($art, (New-Object System.Drawing.Rectangle $dx, $dy, $dw, $dh), $sx, $sy, $sw, $sh, [System.Drawing.GraphicsUnit]::Pixel)
}
# Top image of the welcome and finish pages
Bmp 740 300 { param($g) Put $g 0 175 1672 678 0 0 740 300 } (Join-Path $obj 'hero.bmp')
# Side panel used by Windows' own pages (resume, cancel, error)
Bmp 740 468 {
    param($g)
    $g.Clear([System.Drawing.Color]::White)
    Put $g 1130 0 342 650 0 0 246 468
} (Join-Path $obj 'dialog.bmp')
# Banner of the inner pages
Bmp 740 87 {
    param($g)
    $g.Clear([System.Drawing.Color]::White)
    Put $g 1060 170 420 157 507 0 233 87
    $fade = New-Object System.Drawing.Rectangle 506, 0, 48, 87
    $br = New-Object System.Drawing.Drawing2D.LinearGradientBrush $fade, ([System.Drawing.Color]::White), ([System.Drawing.Color]::FromArgb(0, 255, 255, 255)), 0
    $g.FillRectangle($br, $fade)
} (Join-Path $obj 'banner.bmp')
$art.Dispose()

# --- WiX
& (Join-Path $WixDir 'candle.exe') -nologo -arch x64 -ext WixUIExtension "-dScope=perMachine" "-dEngine=$exe" "-dLib=$libPath" "-dMotion=$motionPath" "-dSrc=$(Join-Path $here 'src')" "-dObj=$obj" -out (Join-Path $obj 'Product.wixobj') (Join-Path $here 'src\Product.wxs')
if ($LASTEXITCODE) { throw 'candle failed' }
$msi = Join-Path $out 'AC Black Flag Resynced - Unity Sprint Mod.msi'
& (Join-Path $WixDir 'light.exe') -nologo -ext WixUIExtension -cultures:en-us -loc (Join-Path $here 'src\en-us.wxl') -spdb -out $msi (Join-Path $obj 'Product.wixobj')
if ($LASTEXITCODE) { throw 'light failed' }
"Built $msi ($((Get-Item $msi).Length) bytes)"
